Type=simple
User=root
WorkingDirectory=${INST_DIR}/${PROJ_DIR}/server
ExecStart=${INST_DIR}/${VENV_NAME}/bin/python main.py
Restart=on-abnormal
RestartSec=10
KillMode=control-group

