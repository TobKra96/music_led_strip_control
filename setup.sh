#!/usr/bin/env bash
set -euo pipefail

# Setup script for MLSC
# https://github.com/TobKra96/music_led_strip_control

if [[ $EUID -eq 0 ]]; then
    echo "Do not run this script as root." >&2
    exit 1
fi

INST_DIR="/share" # Installation location
