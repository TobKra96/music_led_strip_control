    if ! sudo systemctl is-enabled --quiet "${SERVICE_NAME}"; then
        confirm "Do you want to enable autostart for ${PROJ_NAME}"
        if [[ $? -eq 0 ]]; then
            sudo systemctl enable "${SERVICE_NAME}"
            prompt -s "\nAutostart for ${PROJ_NAME} enabled."
        fi
    fi
