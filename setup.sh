# Install uv for managing Python packages and virtual environment:
if [[ -x "$UV_BIN" ]]; then
    # Upgrade uv to the latest version if already installed.
    "$UV_BIN" self update
else
    curl -LsSf https://astral.sh/uv/install.sh | sh
fi

